"""Relay & Network Intelligence (module 11).

SYNTHETIC two-body circular orbits (NOT NASA ephemerides): position of an
orbiter in a Mars-fixed frame from altitude, inclination, RAAN and phase, with
Mars rotation (sidereal day 88 642.663 s). Elevation of the orbiter above the
site's local horizon (spherical Mars) gives contact windows. A store-and-forward
queue then moves the data volume generated by the surface asset through those
windows.
"""
from __future__ import annotations

import math
from dataclasses import asdict, dataclass

import numpy as np

import config as C


@dataclass
class Orbiter:
    name: str = "Relay-1 (MRO-like, synthetic)"
    altitude_km: float = 300.0
    inclination_deg: float = 92.6
    raan_deg: float = 0.0
    phase_deg: float = 0.0
    data_rate_bps: float = 256_000.0
    min_elev_deg: float = 10.0

    def as_dict(self):
        return asdict(self)


DEFAULT_ORBITERS = [
    Orbiter("Relay-A (MRO-like, synthetic)", 300.0, 92.6, 0.0, 0.0, 256_000.0),
    Orbiter("Relay-B (Odyssey-like, synthetic)", 400.0, 93.1, 120.0, 90.0, 128_000.0),
    Orbiter("Relay-C (TGO-like, synthetic)", 400.0, 74.0, 240.0, 200.0, 512_000.0),
]


def period_s(alt_km: float) -> float:
    a = C.R_MARS_MEAN + alt_km * 1e3
    return 2 * math.pi * math.sqrt(a ** 3 / C.GM_MARS)


def ecef_positions(o: Orbiter, t_s: np.ndarray) -> np.ndarray:
    a = C.R_MARS_MEAN + o.altitude_km * 1e3
    n = 2 * math.pi / period_s(o.altitude_km)
    u = math.radians(o.phase_deg) + n * t_s
    i, W = math.radians(o.inclination_deg), math.radians(o.raan_deg)
    x = a * (np.cos(W) * np.cos(u) - np.sin(W) * np.sin(u) * np.cos(i))
    y = a * (np.sin(W) * np.cos(u) + np.cos(W) * np.sin(u) * np.cos(i))
    z = a * (np.sin(u) * np.sin(i))
    rot = -2 * math.pi * t_s / C.SIDEREAL_DAY_S      # inertial -> Mars-fixed
    xe = x * np.cos(rot) - y * np.sin(rot)
    ye = x * np.sin(rot) + y * np.cos(rot)
    return np.stack([xe, ye, z], 1)


def site_vector(lat, lon, h=0.0):
    la, lo = math.radians(lat), math.radians(lon)
    r = C.R_MARS_MEAN + h
    return np.array([r * math.cos(la) * math.cos(lo), r * math.cos(la) * math.sin(lo), r * math.sin(la)])


def elevation_deg(o: Orbiter, lat, lon, t_s):
    pos = ecef_positions(o, t_s)
    s = site_vector(lat, lon)
    up = s / np.linalg.norm(s)
    rel = pos - s
    rng = np.linalg.norm(rel, axis=1)
    return np.degrees(np.arcsin((rel @ up) / rng)), rng


def contact_windows(o: Orbiter, lat, lon, hours: float = 24.66, step_s: float = 20.0) -> dict:
    t = np.arange(0, hours * 3600, step_s)
    el, rng = elevation_deg(o, lat, lon, t)
    vis = el >= o.min_elev_deg
    wins = []
    i = 0
    while i < len(t):
        if vis[i]:
            j = i
            while j + 1 < len(t) and vis[j + 1]:
                j += 1
            wins.append({"start_s": float(t[i]), "end_s": float(t[j]), "duration_s": float(t[j] - t[i] + step_s),
                         "max_elev_deg": float(el[i:j + 1].max()), "min_range_km": float(rng[i:j + 1].min() / 1e3),
                         "volume_mb": float((t[j] - t[i] + step_s) * o.data_rate_bps / 8e6)})
            i = j + 1
        else:
            i += 1
    total = sum(w["duration_s"] for w in wins)
    return {"t_s": t, "elev_deg": el, "range_m": rng, "windows": wins, "availability": total / (hours * 3600),
            "period_min": period_s(o.altitude_km) / 60}


def merge_windows(list_of_windows):
    ev = sorted([(w["start_s"], w["end_s"]) for ws in list_of_windows for w in ws])
    out = []
    for s, e in ev:
        if out and s <= out[-1][1]:
            out[-1][1] = max(out[-1][1], e)
        else:
            out.append([s, e])
    return out


def store_and_forward(gen_rate_bps: float, windows: list[dict], rates_bps: list[float] | float, hours: float,
                      buffer_mb: float = 2000.0, step_s: float = 60.0, outage: tuple | None = None) -> dict:
    """Queue simulation. outage=(start_s, end_s) removes link capacity in that interval."""
    t = np.arange(0, hours * 3600 + step_s, step_s)
    q = np.zeros_like(t, float)
    sent = np.zeros_like(t, float)
    dropped = 0.0
    if not isinstance(rates_bps, list):
        rates_bps = [rates_bps] * len(windows)
    for k in range(1, len(t)):
        q[k] = q[k - 1] + gen_rate_bps * step_s / 8e6
        cap = 0.0
        for w, r in zip(windows, rates_bps):
            if w["start_s"] <= t[k] <= w["end_s"]:
                cap += r * step_s / 8e6
        if outage and outage[0] <= t[k] <= outage[1]:
            cap = 0.0
        out = min(q[k], cap)
        q[k] -= out
        sent[k] = sent[k - 1] + out
        if q[k] > buffer_mb:
            dropped += q[k] - buffer_mb
            q[k] = buffer_mb
    gaps = []
    ends = sorted([(w["start_s"], w["end_s"]) for w in windows])
    prev = 0.0
    for s, e in ends:
        gaps.append(s - prev)
        prev = max(prev, e)
    gaps.append(hours * 3600 - prev)
    return {"t_h": t / 3600, "queue_mb": q, "sent_mb": sent, "dropped_mb": dropped,
            "max_queue_mb": float(q.max()), "max_gap_h": float(max(gaps) / 3600) if gaps else hours,
            "generated_mb": gen_rate_bps * hours * 3600 / 8e6}


def multi_contact(orbiters: list[Orbiter], lat, lon, hours: float = 24.66) -> dict:
    per = []
    allw = []
    for o in orbiters:
        cw = contact_windows(o, lat, lon, hours)
        for w in cw["windows"]:
            w["orbiter"] = o.name
            w["rate_bps"] = o.data_rate_bps
        per.append({"orbiter": o.name, "passes": len(cw["windows"]), "availability": cw["availability"],
                    "period_min": cw["period_min"], "volume_mb": sum(w["volume_mb"] for w in cw["windows"])})
        allw += cw["windows"]
    merged = merge_windows([allw])
    avail = sum(e - s for s, e in merged) / (hours * 3600)
    return {"per_orbiter": per, "windows": sorted(allw, key=lambda w: w["start_s"]), "availability": avail,
            "merged": merged}
